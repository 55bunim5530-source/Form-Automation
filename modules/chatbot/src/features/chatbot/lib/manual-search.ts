type QuestionRoute = {
  test: RegExp;
  category: string;
  preferredSections: string[];
  focusTerms?: string[];
  guide?: { message: string; keyPoints: string[] };
  unavailableMessage?: string;
};

function directRoute(
  test: RegExp,
  category: string,
  preferredSections: string[],
  message: string,
  keyPoints: string[],
  focusTerms: string[] = [],
): QuestionRoute {
  return { test, category, preferredSections, focusTerms, guide: { message, keyPoints } };
}

function unavailableRoute(test: RegExp, message: string): QuestionRoute {
  return { test, category: "unsupported", preferredSections: [], unavailableMessage: message };
}

