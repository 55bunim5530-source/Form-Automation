function normalizeExtractedText(value: string): string {
  return value
    .normalize("NFKC")
    .replace(/사\s+람/gu, "사람")
    .replace(/발견\s+자/gu, "발견자")
    .replace(/실시\s+한다/gu, "실시한다")
    .replace(/범\s+위/gu, "범위")
    .replace(/관\s+할/gu, "관할")
    .replace(/작\s+업/gu, "작업")
    .replace(/근로\s+자/gu, "근로자")
    .replace(/안전\s+보건/gu, "안전보건");
}

function cleanEvidenceLine(rawLine: string): string | undefined {
  const line = normalizeExtractedText(rawLine).replace(/[•◦▪]/g, "·").replace(/\s+/g, " ").trim();
  if (line.length < 8) return undefined;
  if (/[\u3400-\u4DBF\u4E00-\u9FFF\u3040-\u30FF]/u.test(line)) return undefined;

  const latinTokens = line.match(/[A-Za-z]+/g) ?? [];
  const allowedLatin = new Set(["MSDS", "TBM", "PDF", "KF", "MWFS"]);
  if (latinTokens.some((token) => !allowedLatin.has(token.toUpperCase()))) return undefined;
  if (/(제출 인내|신업안전보건지원)/u.test(line)) return undefined;

  const letters = [...line].filter((char) => /\p{L}/u.test(char));
  const hangul = letters.filter((char) => /[가-힣]/u.test(char)).length;
  if (hangul < 5 || (letters.length > 0 && hangul / letters.length < 0.72)) return undefined;

  const unusual = [...line].filter((char) => !/[가-힣A-Za-z0-9\s().,:%/+\-·〈〉]/u.test(char)).length;
  if (unusual > 2) return undefined;

  return line.replace(/^[0-9]+\s+/, "").replace(/\s+([.,:])/g, "$1");
}

function cleanMarkdownLine(rawLine: string): string | undefined {
  const withoutBold = normalizeExtractedText(rawLine).replace(/\*\*/g, "").trim();
  if (!withoutBold) return undefined;
  if (/^\|?(?:\s*:?-+:?\s*\|)+\s*$/u.test(withoutBold)) return undefined;

  if (withoutBold.includes("|")) {
    const cells = withoutBold
      .split("|")
      .map((cell) => cell.replace(/^[□■○◦▪·]+\s*/u, "").replace(/\s+/g, " ").trim())
      .filter(Boolean)
      .filter((cell, index, all) => all.indexOf(cell) === index);
    if (!cells.length) return undefined;
    const compactCells = cells.join("").replace(/\s+/g, "");
    if (/자가진단항목.*(?:네|예).*아니요.*비고/u.test(compactCells)) return undefined;
    return cells.join(" · ");
  }

  return withoutBold.replace(/\s+/g, " ").replace(/\s+\d+\.\s*$/u, "").trim();
}

function excerptFor(text: string, isOcr: boolean): string {
  const paragraphs = text.split(/\n\s*\n/u).map((paragraph) => paragraph
    .split("\n")
    .map(cleanMarkdownLine)
    .filter((line): line is string => Boolean(line))
    .map((line) => isOcr ? cleanEvidenceLine(line) : line)
    .filter((line): line is string => Boolean(line))
    .join(" "))
    .filter(Boolean);
  if (!paragraphs.length) return "자동 문자 인식 품질이 낮은 페이지입니다. 표시된 PDF 쪽의 원문을 직접 확인해 주세요.";
  return paragraphs.join("\n\n");
}

function citedStatement(statement: string, evidenceId: number): string {
  return `${statement.replace(/[.。]\s*$/u, "").trim()} [근거 ${evidenceId}].`;
}

function guideFromRoute(
  pages: Array<{ text: string; isOcr: boolean }>,
  guide: { message: string; keyPoints: string[] },
): { message: string; keyPoints: GroundedPoint[] } | undefined {
  const evidenceTexts = pages.map((page) => normalize(excerptFor(page.text, page.isOcr)).replaceAll(" ", ""));
  const evidenceIdFor = (statement: string): number | undefined => {
    const terms = queryTerms(statement).map((term) => normalize(term).replaceAll(" ", ""));
    const numbers = statement.match(/\d+(?:[.,]\d+)?/gu) ?? [];
    const ranked = evidenceTexts.map((text, index) => ({
      evidenceId: index + 1,
      numberMatch: numbers.every((number) => text.includes(number)),
      score: terms.filter((term) => text.includes(term)).length,
    })).filter((entry) => entry.numberMatch)
      .sort((a, b) => b.score - a.score || a.evidenceId - b.evidenceId);
    const best = ranked[0];
    return best && best.score >= Math.min(2, Math.max(1, terms.length)) ? best.evidenceId : undefined;
  };
  const messageStatements = guide.message
    .split(/(?<=[.!?])\s+/u)
    .map((statement) => statement.trim())
    .filter(Boolean);
  const citedMessages = messageStatements.flatMap((statement) => {
    const evidenceId = evidenceIdFor(statement);
    return evidenceId ? [citedStatement(statement, evidenceId)] : [];
  });
  if (!messageStatements.length || citedMessages.length !== messageStatements.length) return undefined;
  const keyPoints = guide.keyPoints.flatMap((text) => {
    const evidenceId = evidenceIdFor(text);
    return evidenceId ? [{ text, evidenceIds: [evidenceId] }] : [];
  });
  return { message: citedMessages.join(" "), keyPoints };
}

function guideFromEvidence(pages: Array<{ text: string; isOcr: boolean }>, terms: string[], focusTerms: string[] = []): { message: string; keyPoints: GroundedPoint[] } | undefined {
  const statements = pages.flatMap((page, evidenceIndex) => {
    let text = excerptFor(page.text, page.isOcr);
    const answerAt = text.indexOf("답변:");
    if (answerAt >= 0) text = text.slice(answerAt + "답변:".length);
    return text
      .split(/\n{2,}|(?<=[.!?])\s+|(?=[○◦▪■□])/u)
      .map((statement) => statement.replace(/^[○◦▪■□·\-]+\s*/u, "").replace(/\s+/g, " ").replace(/\s+\d+\s*$/u, "").trim())
      .filter((statement) => statement.length >= 8)
      .filter((statement) => !/[?？]$/u.test(statement) && !/^Q\d+[.)]/iu.test(statement))
      .filter((statement) => !/[⇨→]{1,}/u.test(statement))
      .filter((statement) => !/^\d+\s*[·.]\s*[^.!?]{0,45}$/u.test(statement))
      .filter((statement) => !/^(?:제\d+(?:조|장)|[가-힣]+에 관한 사항)$/u.test(statement))
      .filter((statement) => statement.length >= 18 || /(?:한다|합니다|해야|된다|됩니다|있다|있습니다|없다|없습니다|실시|신고|보고|보존|제출|연락)/u.test(statement))
      .map((statement) => ({ statement, evidenceId: evidenceIndex + 1 }));
  });

  if (!statements.length) return undefined;
  const expandedTerms = terms.flatMap((term) => {
    if (term.includes("온라인")) return [term, "원격교육", "인터넷원격교육"];
    if (term.includes("부상자") || term.includes("환자")) return [term, "환자"];
    if (term.includes("보관")) return [term, "저장"];
    if (term.includes("보고")) return [term, "신고"];
    return [term];
  });
  const ordered = statements
    .filter((entry, index, all) => all.findIndex((candidate) => candidate.statement === entry.statement) === index)
    .map((entry, index) => {
      const normalizedStatement = normalize(entry.statement).replaceAll(" ", "");
      const score = expandedTerms.filter((term) => normalizedStatement.includes(normalize(term).replaceAll(" ", ""))).length
        + focusTerms.filter((term) => normalizedStatement.includes(normalize(term).replaceAll(" ", ""))).length * 5;
      return { ...entry, index, score };
    })
    .sort((a, b) => b.score - a.score || a.index - b.index);
  const message = citedStatement(ordered[0].statement, ordered[0].evidenceId);
  const additional = ordered.slice(1, 5).map((entry) => ({ text: entry.statement, evidenceIds: [entry.evidenceId] }));
  return {
    message,
    keyPoints: additional,
  };
}

